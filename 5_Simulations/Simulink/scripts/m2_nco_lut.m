function lut = m2_nco_lut()
%M2_NCO_LUT  64-entry quarter-wave sine ROM of the AERIS-10 NCO.
%
%   Verbatim copy of NCO_SINE_LUT in tb/cosim/fpga_model.py, which in turn
%   mirrors sin_lut in nco_400m_enhanced.v:
%
%       lut(k+1) = round(32767 * sin(k * pi / 128)),   k = 0..63
%
%   Full-scale is therefore 32767 (NOT 32768), and the largest entry is
%   0x7FF5 = 32757 = round(32767*sin(63*pi/128)) -- the peak of a sine is
%   never actually reached by a 64-entry quarter-wave table.
%
%   Returns a 1x64 row vector of doubles.

hex = [ ...
    0x0000, 0x0324, 0x0648, 0x096A, 0x0C8C, 0x0FAB, 0x12C8, 0x15E2, ...
    0x18F9, 0x1C0B, 0x1F1A, 0x2223, 0x2528, 0x2826, 0x2B1F, 0x2E11, ...
    0x30FB, 0x33DF, 0x36BA, 0x398C, 0x3C56, 0x3F17, 0x41CE, 0x447A, ...
    0x471C, 0x49B4, 0x4C3F, 0x4EBF, 0x5133, 0x539B, 0x55F5, 0x5842, ...
    0x5A82, 0x5CB3, 0x5ED7, 0x60EB, 0x62F1, 0x64E8, 0x66CF, 0x68A6, ...
    0x6A6D, 0x6C23, 0x6DC9, 0x6F5E, 0x70E2, 0x7254, 0x73B5, 0x7504, ...
    0x7641, 0x776B, 0x7884, 0x7989, 0x7A7C, 0x7B5C, 0x7C29, 0x7CE3, ...
    0x7D89, 0x7E1D, 0x7E9C, 0x7F09, 0x7F61, 0x7FA6, 0x7FD8, 0x7FF5 ];

lut = double(hex);
end
